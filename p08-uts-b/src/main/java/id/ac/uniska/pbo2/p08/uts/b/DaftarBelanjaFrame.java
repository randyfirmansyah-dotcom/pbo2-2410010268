    public DaftarBelanjaFrame() {
        initComponents();
        
        DecimalFormatSymbols s = new DecimalFormatSymbols(Locale.US);
        s.setGroupingSeparator('.');
        fmt = new DecimalFormat("#,##0", s);

        cmbKategori.setModel(new DefaultComboBoxModel<>(Kategori.values()));
        tblBarang.setModel(model);
        getRootPane().setDefaultButton(btnTambah); // Enter = Tambah

        DefaultTableCellRenderer rupiah = new DefaultTableCellRenderer() {
            @Override
            protected void setValue(Object v) {
                setText(rp((Long) v));
                setHorizontalAlignment(SwingConstants.RIGHT);
            }
        };
        DefaultTableCellRenderer kanan = new DefaultTableCellRenderer();
        kanan.setHorizontalAlignment(SwingConstants.RIGHT);
        tblBarang.getColumnModel().getColumn(2).setCellRenderer(rupiah);
        tblBarang.getColumnModel().getColumn(3).setCellRenderer(kanan);
        tblBarang.getColumnModel().getColumn(4).setCellRenderer(rupiah);

        setLocationRelativeTo(null);
        perbaruiRingkasan();
    }

    private String rp(long n) {
        return "Rp" + fmt.format(n);
    }

    private void perbaruiRingkasan() {
        lblRingkasan.setText("Total " + rp(model.getTotal())
                + ", diskon " + rp(model.getDiskon())
                + ", bayar " + rp(model.getBayar()));
    }

    private void tampilkanError(String pesan, javax.swing.JComponent fokus) {
        lblPesan.setText(pesan);
        fokus.requestFocusInWindow();
    }

